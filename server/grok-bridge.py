#!/usr/bin/env python3
"""Minimal Grok Bot -> jade-py bridge (Python equivalent).

Expects:
  JADE_API_URL   http://localhost:8760/v1/chat
  JADE_API_TOKEN generated by jade-py (or read from server/.token)
  GROK_PORT      8780 (optional)
"""

import json
import os
import sys
import urllib.request
from http.server import BaseHTTPRequestHandler, HTTPServer
from pathlib import Path

JADE_API_URL = os.environ.get("JADE_API_URL", "http://localhost:8760/v1/chat")
GROK_PORT = int(os.environ.get("GROK_PORT", "8780"))


def read_token() -> str:
    if os.environ.get("JADE_API_TOKEN"):
        return os.environ["JADE_API_TOKEN"]
    for candidate in [Path(__file__).with_name(".token"), Path.cwd() / ".token"]:
        try:
            return candidate.read_text().strip()
        except OSError:
            pass
    return ""


JADE_API_TOKEN = read_token()


def forward(method: str, target_url: str, body: dict | None = None) -> dict:
    data = json.dumps(body).encode() if body else None
    headers = {
        "Content-Type": "application/json",
        "Accept": "application/json",
    }
    if JADE_API_TOKEN:
        headers["Authorization"] = f"Bearer {JADE_API_TOKEN}"
    req = urllib.request.Request(target_url, data=data, headers=headers, method=method)
    with urllib.request.urlopen(req, timeout=120) as resp:
        return json.loads(resp.read().decode())


class Handler(BaseHTTPRequestHandler):
    def log_message(self, fmt, *args):
        print(f"[{self.log_date_time_string()}] {fmt % args}")

    def _json(self, status: int, payload: dict):
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.end_headers()
        self.wfile.write(json.dumps(payload).encode())

    def do_GET(self):
        if self.path == "/health":
            self._json(200, {"ok": True})
        else:
            self._json(404, {"ok": False, "error": "unknown endpoint"})

    def do_POST(self):
        if self.path not in ("/v1", "/v1/chat"):
            self._json(404, {"ok": False, "error": "unknown endpoint"})
            return
        length = int(self.headers.get("Content-Length", "0"))
        body = self.rfile.read(length).decode()
        try:
            payload = json.loads(body)
        except json.JSONDecodeError as e:
            self._json(400, {"ok": False, "error": f"invalid JSON: {e}"})
            return
        message = payload.get("message") or payload.get("prompt") or payload.get("text") or ""
        if not message:
            self._json(400, {"ok": False, "error": "missing_message"})
            return
        try:
            result = forward("POST", JADE_API_URL, {"message": message, "stream": False})
            self._json(200, result)
        except Exception as e:
            self._json(502, {"ok": False, "error": str(e)})


def main():
    server = HTTPServer(("", GROK_PORT), Handler)
    print(f"Grok bridge listening on port {GROK_PORT}")
    print(f"Forwarding to {JADE_API_URL}")
    print(f"Token: {'loaded' if JADE_API_TOKEN else 'missing'}")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nShutting down.")
        server.shutdown()


if __name__ == "__main__":
    main()
